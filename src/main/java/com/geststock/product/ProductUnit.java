package com.geststock.product;

/** Unité de vente d'un produit (contrainte {@code ck_product_unit}). */
public enum ProductUnit {

	/** À la pièce (monture, accessoire). */
	UNIT,

	/** À la paire (verres correcteurs). */
	PAIR,

	/** À la boîte (lentilles de contact). */
	BOX,

	/** Au flacon (solutions d'entretien). */
	BOTTLE

}
